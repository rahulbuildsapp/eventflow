import os

# --- load .env ourselves, BEFORE seeding any defaults --------------------
# python-decouple checks os.environ *before* the .env file (decouple.py:86).
# So if we blindly os.environ.setdefault() here, our placeholders would land in
# os.environ first and the project's real .env would be silently ignored.
# Loading it here first means an explicit .env always wins, and we only fill
# in keys the file doesn't define.
def _load_dotenv(path: str) -> None:
    if not os.path.exists(path):
        return
    with open(path, encoding="utf-8") as fh:
        for raw in fh:
            line = raw.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            key, _, value = line.partition("=")
            key = key.strip()
            value = value.strip().strip('"').strip("'")
            # real environment always wins over the file
            os.environ.setdefault(key, value)


